-- 1) Create a public bucket for PDFs (20 MB per file is enforced in the website UI).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('notes-pdf', 'notes-pdf', true, 20971520, array['application/pdf'])
on conflict (id) do update set public = true;

-- 2) Notes catalogue. Anyone can read; only authenticated admin can add/edit/delete.
create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  title text not null,
  subject text not null check (subject in ('हिंदी','English','गणित','विज्ञान','सामाजिक विज्ञान','संस्कृत')),
  file_url text not null,
  storage_path text not null,
  created_at timestamptz not null default now()
);

alter table public.notes enable row level security;

drop policy if exists "Anyone can read notes" on public.notes;
create policy "Anyone can read notes" on public.notes
for select to anon, authenticated using (true);

-- IMPORTANT: Replace ADMIN_USER_UUID with the Auth user's UUID after creating the admin account.
drop policy if exists "Admin can manage notes" on public.notes;
create policy "Admin can manage notes" on public.notes
for all to authenticated
using (auth.uid() = 'ADMIN_USER_UUID'::uuid)
with check (auth.uid() = 'ADMIN_USER_UUID'::uuid);

-- Storage: public can read PDFs; only this admin account can upload/change/delete.
drop policy if exists "Anyone can read notes PDFs" on storage.objects;
create policy "Anyone can read notes PDFs" on storage.objects
for select to anon, authenticated
using (bucket_id = 'notes-pdf');

drop policy if exists "Admin can upload notes PDFs" on storage.objects;
create policy "Admin can upload notes PDFs" on storage.objects
for insert to authenticated
with check (bucket_id = 'notes-pdf' and (storage.foldername(name))[1] = auth.uid()::text
and auth.uid() = 'ADMIN_USER_UUID'::uuid);

drop policy if exists "Admin can update notes PDFs" on storage.objects;
create policy "Admin can update notes PDFs" on storage.objects
for update to authenticated
using (bucket_id = 'notes-pdf' and auth.uid() = 'ADMIN_USER_UUID'::uuid)
with check (bucket_id = 'notes-pdf' and auth.uid() = 'ADMIN_USER_UUID'::uuid);

drop policy if exists "Admin can delete notes PDFs" on storage.objects;
create policy "Admin can delete notes PDFs" on storage.objects
for delete to authenticated
using (bucket_id = 'notes-pdf' and auth.uid() = 'ADMIN_USER_UUID'::uuid);
